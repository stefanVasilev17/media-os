create table episode_review_revision (
    package_id uuid not null references episode_package_import(id),
    item_id uuid not null,
    revision integer not null check(revision between 1 and 100),
    kind varchar(24) not null check(kind in ('STRENGTH','PROBLEM','LESSON','RULE','RECOMMENDATION','ANALYTICS','CONCLUSION')),
    category varchar(24) not null check(category in ('VISUAL','STORY','TECHNICAL','VOICE','PRODUCTION','PUBLISHING','REELS','DISTRIBUTION','AUDIENCE')),
    scope varchar(12) not null check(scope in ('EPISODE','CHANNEL')),
    classification varchar(24) not null check(classification in ('OBSERVATION','HYPOTHESIS','VERIFIED_RESULT','PERMANENT_RULE')),
    title varchar(200) not null,
    body text not null check(octet_length(body)<=16384),
    applicability text not null check(octet_length(applicability)<=4096),
    evidence text not null check(octet_length(evidence)<=8192),
    metric varchar(40),
    value numeric(20,6),
    currency varchar(3),
    period_start date,
    period_end date,
    state varchar(12) not null check(state in ('DRAFT','APPROVED','RETIRED')),
    master_sha256 varchar(64) not null check(master_sha256 ~ '^[a-f0-9]{64}$'),
    context_sha256 varchar(64) not null check(context_sha256 ~ '^[a-f0-9]{64}$'),
    actor varchar(256) not null,
    audit_id uuid not null,
    recorded_at timestamptz not null default now(),
    primary key(package_id,item_id,revision),
    check((kind='ANALYTICS')=(metric is not null and period_start is not null and period_end is not null)),
    check(period_start is null or period_end>=period_start),
    check((classification='PERMANENT_RULE')=(kind='RULE')),
    check(kind<>'RULE' or scope='CHANNEL'),
    check(kind not in ('ANALYTICS','CONCLUSION') or scope='EPISODE')
);
create index episode_review_latest_idx on episode_review_revision(package_id,item_id,revision desc);
