export function requireSupportedTargetComposition(value){
  if(typeof value!=='string'||(value!==''&&!supportedTargetCompositions.has(value))){
    throw new Error('REMOTION_WORKER_TARGET_COMPOSITION_INVALID');
  }
  return value;
}
