import {useEffect,useState} from 'react';
import {ExternalLink,PlayCircle,RefreshCcw} from 'lucide-react';

const ENDPOINT='/api/v1/remotion/renders/ep003/shot03/v2/latest-successful';
const PREFIX='/api/v1/remotion/renders/';
const COMPOSITION='EP003-SHOT03-DATABASE-REPLICAS-V2-DIRECTOR-CANDIDATE';
const RENDER_KEY='EP003_SHOT03_DATABASE_REPLICAS_V2';
const UUID=/^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{4}-[a-f0-9]{12}$/i;

type RecordV2={
  status?:string;renderId?:string;renderKey?:string;compositionId?:string;
  videoUrl?:string;profile?:string;fps?:number;width?:number;height?:number;
  durationInFrames?:number;sizeBytes?:number;directorLocked?:boolean;
};
type State={kind:'CHECKING'|'READY'|'EMPTY';record?:RecordV2;message?:string};

export function Ep003Shot03V2DirectorReview(){
  const [revision,setRevision]=useState(0);
  const [state,setState]=useState<State>({kind:'CHECKING'});
  useEffect(()=>{
    const ctrl=new AbortController();
    setState({kind:'CHECKING'});
    void fetch(ENDPOINT,{cache:'no-store',signal:ctrl.signal})
      .then(async response=>{
        if(!response.ok)throw Error('SHOT03 V2 saved video lookup HTTP '+response.status);
        return response.json() as Promise<RecordV2>;
      })
      .then(record=>{
        if(ctrl.signal.aborted)return;
        if(record.status==='EMPTY'){
          setState({kind:'EMPTY',message:'SHOT03 V2 render is not saved yet. V1 remains available in the historical section below.'});
          return;
        }
        if(record.status!=='READY'||!record.renderId||!UUID.test(record.renderId)||
          record.renderKey!==RENDER_KEY||record.compositionId!==COMPOSITION||
          record.profile!=='REVIEW'||record.width!==1920||record.height!==1080||
          record.fps!==30||record.durationInFrames!==3080||
          record.videoUrl!==PREFIX+record.renderId+'/video'||
          !record.sizeBytes||record.sizeBytes<1000000||
          record.directorLocked===true){
          setState({kind:'EMPTY',message:'The V2 candidate fails the exact verified saved MP4 contract. No fallback and no auto-lock.'});
          return;
        }
        setState({kind:'READY',record});
      })
      .catch(error=>{
        if(!ctrl.signal.aborted)setState({kind:'EMPTY',message:error instanceof Error?error.message:String(error)});
      });
    return ()=>ctrl.abort();
  },[revision]);

  const video=state.kind==='READY'?state.record?.videoUrl:null;
  return <section className="ep003-director-review" aria-label="EP003 SHOT03 V2 Director review video">
    <header className="ep003-director-review-heading">
      <div>
        <h3><PlayCircle size={21} aria-hidden="true"/> SHOT03 V2 · Director Video Review</h3>
        <p>One Primary. Two Replicas. · Compact database glyphs</p>
      </div>
      <span className="ep003-director-review-status">V2 · RENDERED CANDIDATE · NOT LOCKED</span>
    </header>
    <p className="ep003-director-review-detail">
      New compact cylindrical database nodes for Replica A and Replica B instead of
      generic blue service containers. The Primary, original Login request paths,
      all 13 real spoken anchors, original Slow Natural voice and seamless SHOT02 V4
      frame-zero transition are preserved. 1:42.67 · 1920×1080 · 30 fps.
      Review the visible database identity, replication routes and first-second motion.
    </p>
    {state.kind==='CHECKING'&&<p role="status">Checking stored SHOT03 V2 MP4…</p>}
    {state.kind==='EMPTY'&&<p role="status">{state.message}</p>}
    {video&&<video key={video} className="ep003-director-review-video"
      controls playsInline preload="metadata" src={video}
      aria-label="EP003 SHOT03 V2 database replicas Director review video">
      Your browser cannot play the MP4. Open it in a new tab.
    </video>}
    <nav className="ep003-director-review-actions" aria-label="SHOT03 V2 review actions">
      {video&&<a href={video} target="_blank" rel="noopener noreferrer">
        <ExternalLink size={16} aria-hidden="true"/> Open SHOT03 V2 MP4
      </a>}
      <button type="button" onClick={()=>setRevision(x=>x+1)}>
        <RefreshCcw size={15} aria-hidden="true"/> Refresh SHOT03 V2
      </button>
    </nav>
    <p className="ep003-director-review-caution">
      Only you can Director-LOCK SHOT03 V2 after viewing this exact MP4.
      SHOT01 V2 and SHOT02 V4 remain immutable; no paid narration or video is generated by this player.
    </p>
  </section>;
}
